from __future__ import annotations

from datetime import datetime
from typing import Any

from pydantic import BaseModel, Field


class OutboxRecord(BaseModel):
    """
    Durable authorization outbox record.

    outbox_seq is generated by SQLite AUTOINCREMENT.
    It must never be generated with application-side max+1 logic.

    verifkv_seq remains NULL until the record is folded into the
    VerifKV hash chain.
    """

    outbox_seq: int | None = None

    authorization_event_id: str = Field(min_length=1)

    request_id: str = Field(min_length=1)

    tenant_id: str = Field(min_length=1)

    decision: bool

    backend_id: str = Field(min_length=1)

    zone: str = Field(min_length=1)

    decision_id: str = Field(min_length=1)

    policy_version: str = Field(min_length=1)

    timestamp: datetime

    payload: dict[str, Any] = Field(default_factory=dict)

    verifkv_seq: int | None = None


OUTBOX_TABLE_DDL = """
CREATE TABLE IF NOT EXISTS authz_outbox (
    outbox_seq INTEGER PRIMARY KEY AUTOINCREMENT,

    authorization_event_id TEXT NOT NULL UNIQUE,

    request_id TEXT NOT NULL,

    tenant_id TEXT NOT NULL,

    decision INTEGER NOT NULL,

    backend_id TEXT NOT NULL,

    zone TEXT NOT NULL,

    decision_id TEXT NOT NULL,

    policy_version TEXT NOT NULL,

    timestamp TEXT NOT NULL,

    payload TEXT NOT NULL,

    verifkv_seq INTEGER NULL
);

CREATE INDEX IF NOT EXISTS idx_outbox_unreconciled
ON authz_outbox(outbox_seq)
WHERE verifkv_seq IS NULL;
"""
